export type Line = [number, number, number, number];

/*  The caption is lettered by the same head, in the same pass — so it
    can never sit wrong relative to the figure. */
export function letterPaths(
  text: string,
  cx: number,
  baseY: number,
  size: number,
): Line[] {
  const out: Line[] = [];
  const tr = size * 0.62; // glyph width
  const gapw = size * 0.3; // tracking

  let total = 0;
  for (const ch of text) total += (ch === " " ? tr * 0.55 : tr) + gapw;
  total -= gapw;

  let x = cx - total / 2;
  for (const ch of text) {
    const gl = GLYPH[ch] ?? GLYPH[" "];
    const gw = ch === " " ? tr * 0.55 : tr;
    for (const poly of gl) {
      for (let i = 0; i < poly.length - 2; i += 2) {
        out.push([
          x + poly[i] * gw,
          baseY + poly[i + 1] * size,
          x + poly[i + 2] * gw,
          baseY + poly[i + 3] * size,
        ]);
      }
    }
    x += gw + gapw;
  }
  return out;
}
